"""Write the synthetic market universe to CSV.

Usage::

    python -m market_sim.generate_data --seed 42 --n-markets 50 --out output/synthetic_markets.csv

The file is fully determined by ``--seed`` and ``--n-markets``; re-running with
the same arguments reproduces it byte for byte. Every row carries
``data_source=synthetic`` and the file starts with a comment line saying so.
"""

from __future__ import annotations

import argparse
import csv
from collections.abc import Sequence
from pathlib import Path

from market_sim.markets import DEFAULT_SEED, MarketConfig, SyntheticMarket, generate_universe

COLUMNS = (
    "data_source",
    "market_id",
    "tier",
    "global_step",
    "local_step",
    "true_prob",
    "mid",
    "best_bid",
    "best_ask",
    "top_depth",
    "volume",
    "buy_flow",
    "sell_flow",
    "fundamental_z",
    "poll_z",
    "outcome",
)


def write_csv(markets: Sequence[SyntheticMarket], path: Path, seed: int) -> int:
    """Write one row per (market, step). Returns the number of data rows written."""
    path.parent.mkdir(parents=True, exist_ok=True)
    rows = 0
    with path.open("w", newline="") as fh:
        fh.write(
            f"# SYNTHETIC DATA generated by market_sim/generate_data.py (seed={seed}). "
            "Not real market data.\n"
        )
        writer = csv.writer(fh)
        writer.writerow(COLUMNS)
        for m in markets:
            for i in range(m.length):
                bid, ask = m.touch(i)
                writer.writerow(
                    [
                        "synthetic",
                        m.market_id,
                        m.tier.value,
                        m.open_step + i,
                        i,
                        f"{m.true_prob[i]:.6f}",
                        f"{m.mid[i]:.6f}",
                        f"{bid / 100:.2f}",
                        f"{ask / 100:.2f}",
                        f"{m.top_depth[i]:.2f}",
                        int(m.volume[i]),
                        int(m.buy_flow[i]),
                        int(m.sell_flow[i]),
                        f"{m.fundamental_z[i]:.6f}",
                        f"{m.poll_z[i]:.6f}",
                        m.outcome,
                    ]
                )
                rows += 1
    return rows


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument("--n-markets", type=int, default=50)
    parser.add_argument("--out", type=Path, default=Path("output/synthetic_markets.csv"))
    args = parser.parse_args(argv)
    markets = generate_universe(MarketConfig(n_markets=args.n_markets, seed=args.seed))
    rows = write_csv(markets, args.out, args.seed)
    print(f"wrote {rows} synthetic rows for {len(markets)} markets to {args.out}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
